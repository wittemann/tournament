/**
 * Turns a checked schedule input into one SQL script (docs/schedule-load.md).
 * Pure: the script is applied by hand via the Supabase MCP.
 */
import { CLASS_ORDER, classRank } from '@/lib/classOrder';
import { numberGames, type ScheduleInput } from '@/lib/scheduleCheck';

/** A string literal. Control characters are rejected by the checker. */
export const sqlString = (s: string) => `'${s.replace(/'/g, "''")}'`;

const lit = (s: string | null) => (s === null ? 'null' : sqlString(s));
const num = (n: number | null) => (n === null ? 'null' : String(n));

/**
 * Replaces halls, teams and games (items and faq stay) in one transaction,
 * children first for the foreign keys, parents first on insert. Games are
 * inserted in schedule order so ids ascend with the schedule. The closing
 * `do` block aborts the transaction if the row counts are off.
 */
export function scheduleToSql(input: ScheduleInput): string {
  const games = numberGames(input);
  const halls = input.halls.map((h, i) => `  (${sqlString(h)}, ${i + 1})`);
  const teams: string[] = [];
  const classes = Object.keys(input.teams).sort(
    (a, b) => classRank(a) - classRank(b),
  );
  for (const cls of classes)
    for (const [group, names] of Object.entries(input.teams[cls]))
      for (const name of names)
        teams.push(
          `  (${sqlString(name)}, ${sqlString(cls)}, ${sqlString(group)})`,
        );
  const rows = games.map(
    (g) =>
      `  (${[
        num(g.number),
        lit(g.stage),
        lit(g.label),
        lit(g.hometeam),
        lit(g.awayteam),
        lit(g.home_ref),
        lit(g.away_ref),
        lit(g.scorer),
        lit(g.scorer_class),
        lit(g.class),
        lit(g.time),
        lit(g.location),
        lit(g.eventname),
      ].join(', ')})`,
  );

  return [
    '-- Generated by scripts/schedule-to-sql.ts. Replaces halls, teams and games;',
    '-- items and faq are left alone. Back up the current data first (docs/schedule-load.md).',
    `-- ${halls.length} halls, ${teams.length} teams, ${rows.length} games and events (classes known: ${CLASS_ORDER.join(', ')}).`,
    'begin;',
    '',
    'delete from public.games;',
    'delete from public.teams;',
    'delete from public.halls;',
    '',
    'insert into public.halls (name, sort) values',
    halls.join(',\n') + ';',
    '',
    'insert into public.teams (name, class, group_name) values',
    teams.join(',\n') + ';',
    '',
    'insert into public.games',
    '  (number, stage, label, hometeam, awayteam, home_ref, away_ref, scorer, scorer_class, class, time, location, eventname)',
    'values',
    rows.join(',\n') + ';',
    '',
    'do $$',
    'begin',
    `  if (select count(*) from public.halls) <> ${halls.length}`,
    `    or (select count(*) from public.teams) <> ${teams.length}`,
    `    or (select count(*) from public.games) <> ${rows.length} then`,
    "    raise exception 'row counts after the load do not match the schedule file';",
    '  end if;',
    'end $$;',
    '',
    'commit;',
    '',
  ].join('\n');
}
